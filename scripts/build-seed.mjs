#!/usr/bin/env node
/**
 * Build a fresh snapshot for the Projetract landing board.
 * Uses the authenticated `gh` CLI, so no token ever lives in this repo.
 *
 *   node scripts/build-seed.mjs [username] [--months=24]
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");

const args = process.argv.slice(2);
const user = args.find((a) => !a.startsWith("--")) || "lulgabc";
const monthsArg = args.find((a) => a.startsWith("--months="));
const months = monthsArg ? Number(monthsArg.split("=")[1]) : 24;
const cutoff = new Date();
cutoff.setMonth(cutoff.getMonth() - months);

const gh = (path) =>
  JSON.parse(
    execFileSync("gh", ["api", path], {
      encoding: "utf8",
      maxBuffer: 20 * 1024 * 1024,
    })
  );

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function commitActivity(fullName) {
  for (let attempt = 0; attempt < 4; attempt++) {
    const result = gh(`repos/${fullName}/stats/commit_activity`);
    if (Array.isArray(result) && result.length) return { weeks: result, partial: false };
    await sleep(1400 + attempt * 900);
  }
  // GitHub sometimes refuses to warm the stats cache. Derive a partial but real
  // picture from the most recent 100 commits instead of inventing data.
  try {
    const commits = gh(`repos/${fullName}/commits?per_page=100`);
    const buckets = new Map();
    for (const c of commits) {
      const date = new Date(c.commit.author?.date || c.commit.committer?.date);
      if (!date || Number.isNaN(date.getTime())) continue;
      const sunday = new Date(date);
      sunday.setUTCHours(0, 0, 0, 0);
      sunday.setUTCDate(sunday.getUTCDate() - sunday.getUTCDay());
      const key = sunday.getTime();
      if (!buckets.has(key)) buckets.set(key, [0, 0, 0, 0, 0, 0, 0]);
      buckets.get(key)[date.getUTCDay()] += 1;
    }
    const weeks = [...buckets.entries()]
      .sort((a, b) => a[0] - b[0])
      .map(([week, days]) => ({
        week: week / 1000,
        days,
        total: days.reduce((a, b) => a + b, 0),
      }));
    return { weeks, partial: true };
  } catch {
    return { weeks: [], partial: true };
  }
}

function openCounts(fullName) {
  try {
    const issues = gh(`repos/${fullName}/issues?state=open&per_page=100`);
    const pulls = gh(`repos/${fullName}/pulls?state=open&per_page=100`);
    return {
      openIssues: issues.filter((i) => !i.pull_request).length,
      openPRs: pulls.length,
    };
  } catch {
    return { openIssues: null, openPRs: null };
  }
}

console.log(`Fetching public repos for @${user} pushed since ${cutoff.toISOString().slice(0, 10)}…`);
const repos = gh(`users/${user}/repos?sort=pushed&per_page=100`)
  .filter((r) => !r.fork && !r.archived && r.visibility === "public")
  .filter((r) => new Date(r.pushed_at) >= cutoff);

console.log(`Found ${repos.length} repos.`);

const snapshots = [];
for (const [index, repo] of repos.entries()) {
  process.stdout.write(`  [${index + 1}/${repos.length}] ${repo.full_name} … `);
  let languages = {};
  try {
    languages = gh(`repos/${repo.full_name}/languages`);
  } catch {}
  const activity = await commitActivity(repo.full_name);
  const counts = openCounts(repo.full_name);

  snapshots.push({
    full_name: repo.full_name,
    name: repo.name,
    owner: repo.owner.login,
    description: (repo.description || "").trim(),
    homepage: repo.homepage || "",
    language: repo.language || null,
    topics: repo.topics || [],
    license: repo.license?.spdx_id || null,
    default_branch: repo.default_branch || "main",
    stars: repo.stargazers_count || 0,
    forks: repo.forks_count || 0,
    watchers: repo.watchers_count || 0,
    open_issues_total: repo.open_issues_count || 0,
    open_issues: counts.openIssues,
    open_prs: counts.openPRs,
    created_at: repo.created_at,
    updated_at: repo.updated_at,
    pushed_at: repo.pushed_at,
    size: repo.size || 0,
    archived: !!repo.archived,
    visibility: repo.visibility || "public",
    languages,
    weeks: activity.weeks.map((w) => ({
      start: w.week * 1000,
      total: w.total || 0,
      days: w.days || [0, 0, 0, 0, 0, 0, 0],
    })),
    activity_partial: activity.partial,
  });

  console.log(`${activity.weeks.length} weeks${activity.partial ? " (partial)" : ""}, ${counts.openIssues ?? "?"} issues, ${counts.openPRs ?? "?"} PRs`);
}

const payload = {
  schema: 1,
  generated_at: new Date().toISOString(),
  user,
  repos: snapshots,
};

const target = join(root, "seed.js");
writeFileSync(
  target,
  `/* Generated by scripts/build-seed.mjs — a point-in-time snapshot of @${user}'s public work. */\nwindow.PROJETRACT_SEED = ${JSON.stringify(payload, null, 1)};\n`
);
console.log(`\nWrote ${target} (${(Buffer.byteLength(JSON.stringify(payload)) / 1024).toFixed(1)} KB, ${snapshots.length} repos).`);
